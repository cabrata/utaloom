    /**
     * Auto-detect dominant Asian lyric language per SONG, not per line.
     * Prevents Kanji-only Japanese lines in anime/J-pop songs from being misdetected as Chinese.
     */
    fun detectSongLanguage(fullSongText: String): String? {
        val hangulCount = fullSongText.count { it in '\uAC00'..'\uD7A3' }
        val kanaCount = fullSongText.count { (it in '\u3040'..'\u309F') || (it in '\u30A0'..'\u30FF') }
        val cjkCount = fullSongText.count { it in '\u4E00'..'\u9FFF' }

        return when {
            hangulCount > 0 && hangulCount >= kanaCount && hangulCount >= cjkCount -> "ko"
            kanaCount > 0 -> "ja"
            cjkCount > 0 -> "zh"
            hangulCount > 0 -> "ko"
            else -> null
        }
    }

    /** Resolves the effective target language given an explicit or automatic selector. */
    fun resolveLanguage(fullSongText: String, selector: String): String? = when (selector.trim().lowercase()) {
        "ja" -> "ja"
        "ko" -> "ko"
        "zh" -> "zh"
        "auto" -> detectSongLanguage(fullSongText)
        else -> null
    }

    private fun hiraganaToKatakana(text: String): String = buildString(text.length) {
        for (ch in text) {
            if (ch in '\u3041'..'\u3096') append((ch.code + 0x60).toChar()) else append(ch)
        }
    }

    fun katakanaToRomaji(katakana: String?, nextKatakana: String? = null): String {
        if (katakana.isNullOrEmpty()) return ""
        val normalized = hiraganaToKatakana(katakana)
        val romajiBuilder = StringBuilder(normalized.length)
        var i = 0
        val n = normalized.length
        while (i < n) {
            var consumed = false
            if (i + 1 < n) {
                val two = normalized.substring(i, i + 2)
                val mapped = KANA_ROMAJI_MAP[two]
                if (mapped != null) {
                    romajiBuilder.append(mapped)
                    i += 2
                    consumed = true
                }
            }
            if (!consumed && normalized[i] == 'ッ') {
                val nextChar = if (i + 1 < n) normalized[i + 1] else nextKatakana?.let { hiraganaToKatakana(it) }?.getOrNull(0)
                if (nextChar != null) {
                    val nextRomaji = KANA_ROMAJI_MAP[nextChar.toString()]
                    val doubled = nextRomaji?.getOrNull(0)?.toString() ?: nextChar.toString()
                    romajiBuilder.append(doubled.lowercase().trim())
                }
                i += 1
                consumed = true
            }
            if (!consumed) {
                val one = normalized[i].toString()
                romajiBuilder.append(KANA_ROMAJI_MAP[one] ?: one)
                i += 1
            }
        }
        return romajiBuilder.toString().lowercase(Locale.ROOT)
    }

    suspend fun romanizeJapanese(text: String): String = withContext(Dispatchers.Default) {
        if (text.isBlank()) return@withContext text
        val tokens = kuromojiTokenizer.tokenize(text)
        val romanizedTokens = tokens.mapIndexed { index, token ->
            val currentReading = if (token.reading.isNullOrEmpty() || token.reading == "*") {
                token.surface
            } else {
                token.reading
            }
            val nextReading = if (index + 1 < tokens.size) {
                tokens[index + 1].reading?.takeIf { it.isNotEmpty() && it != "*" } ?: tokens[index + 1].surface
            } else null
            katakanaToRomaji(currentReading, nextReading)
        }
        romanizedTokens.joinToString(" ").replace(Regex("\\s+"), " ").trim()
    }

    suspend fun romanizeKorean(text: String): String = withContext(Dispatchers.Default) {
        if (text.isBlank()) return@withContext text
        val romajaBuilder = StringBuilder()
        var prevFinal: String? = null

        for (i in text.indices) {
            val char = text[i]
            if (char in '\uAC00'..'\uD7A3') {
                val syllableIndex = char.code - 0xAC00
                val choIndex = syllableIndex / (21 * 28)
                val jungIndex = (syllableIndex % (21 * 28)) / 28
                val jongIndex = syllableIndex % 28

                val choChar = (0x1100 + choIndex).toChar().toString()
                val jungChar = (0x1161 + jungIndex).toChar().toString()
                val jongChar = if (jongIndex == 0) null else (0x11A7 + jongIndex).toChar().toString()

                if (prevFinal != null) {
                    val contextKey = prevFinal + choChar
                    val jong = HANGUL_ROMAJA_MAP["jong"]?.get(contextKey)
                        ?: HANGUL_ROMAJA_MAP["jong"]?.get(prevFinal)
                        ?: prevFinal
                    romajaBuilder.append(jong)
                }

                val cho = HANGUL_ROMAJA_MAP["cho"]?.get(choChar) ?: choChar
                val jung = HANGUL_ROMAJA_MAP["jung"]?.get(jungChar) ?: jungChar
                romajaBuilder.append(cho).append(jung)
                prevFinal = jongChar
            } else {
                if (prevFinal != null) {
                    val jong = HANGUL_ROMAJA_MAP["jong"]?.get(prevFinal) ?: prevFinal
                    romajaBuilder.append(jong)
                    prevFinal = null
                }
                romajaBuilder.append(char)
            }
        }

        if (prevFinal != null) {
            val jong = HANGUL_ROMAJA_MAP["jong"]?.get(prevFinal) ?: prevFinal
            romajaBuilder.append(jong)
        }

        romajaBuilder.toString()
    }

    suspend fun romanizeChinese(text: String): String = withContext(Dispatchers.Default) {
        if (text.isBlank()) return@withContext text
        val builder = StringBuilder(text.length * 2)
        for (ch in text) {
            if (ch in '\u4E00'..'\u9FFF') {
                val py = Pinyin.toPinyin(ch).lowercase(Locale.ROOT)
                builder.append(py).append(' ')
            } else {
                builder.append(ch)
            }
        }
        builder.toString()
            .replace(Regex("\\s+([,.!?;:])"), "$1")
            .replace(Regex("\\s+([，。！？；：、（）《》〈〉【】『』「」])"), "$1")
            .replace(Regex("\\s+"), " ")
            .trim()
    }

    /**
     * Romanizes all lines of a song using the song's resolved language.
     * Retains exact line count and indices so secondary lines map cleanly to original karaoke timings.
     */
    suspend fun romanizeSongLines(
        lines: List<String>,
        languageSelector: String = "auto",
    ): List<String?>? = withContext(Dispatchers.Default) {
        val fullText = lines.joinToString("\n")
        val lang = resolveLanguage(fullText, languageSelector) ?: return@withContext null

        lines.map { line ->
            if (line.isBlank()) return@map null
            val romanized = when (lang) {
                "ja" -> romanizeJapanese(line)
                "ko" -> romanizeKorean(line)
                "zh" -> romanizeChinese(line)
                else -> null
            }
            if (romanized == null || romanized.trim().equals(line.trim(), ignoreCase = true)) {
                null
            } else {
                romanized
            }
        }
    }
